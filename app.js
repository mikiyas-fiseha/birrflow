function detectBank(text) {
  const lower = text.toLowerCase();
  if (lower.includes("telebirr")) return "Telebirr";
  if (lower.includes("m-pesa") || lower.includes("mpesa")) return "M-PESA";
  if (lower.includes("cbe birr")) return "CBE Birr";
  if (lower.includes("abyssinia")) return "Bank of Abyssinia";
  if (lower.includes("dashen")) return "Dashen Bank";
  if (lower.includes("awash")) return "Awash Bank";
  if (lower.includes("wegagen")) return "Wegagen Bank";
  if (lower.includes("abay")) return "Abay Bank";
  if (lower.includes("coop") || lower.includes("cooperative")) return "Coopbank";
  if (lower.includes("oromia")) return "Oromia Bank";
  if (lower.includes("amhara")) return "Amhara Bank";
  return "CBE";
}

function parseSms(text) {
  const bank = detectBank(text);
  const amtMatch = text.match(/(?:ETB|Birr|ብር)\s*([\d,]+(?:\.\d{1,2})?)/i) || text.match(/([\d,]+(?:\.\d{1,2})?)\s*(?:ETB|Birr|ብር)/i);
  const amount = amtMatch ? parseFloat(amtMatch[1].replace(/,/g, "")) : 1000;

  const lower = text.toLowerCase();
  const isExpense =
    lower.includes("debited") ||
    lower.includes("paid") ||
    lower.includes("sent") ||
    lower.includes("withdrawn") ||
    lower.includes("transfer to");
  const type = isExpense ? "expense" : "income";

  const partyMatch = text.match(/(?:from|to)\s+([A-Za-z0-9\s.&'-]{3,32}?)(?:\s+on|\s+via|\.|$)/i);
  const party = partyMatch ? partyMatch[1].trim() : type === "income" ? "Incoming Transfer" : "Outgoing Payment";

  const now = new Date();
  const timeStr = now.toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });
  const date = `Today · ${timeStr}`;

  return { id: Date.now(), bank, type, amount, party, date };
}

function formatETB(num) {
  return num.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

function renderParsedPreview(tx) {
  const el = document.getElementById("parsedPreview");
  const isAm = currentLang === "am";
  const typeLabel =
    tx.type === "income"
      ? isAm ? "ገቢ (Income)" : "Income"
      : isAm ? "ወጪ (Expense)" : "Expense";

  el.innerHTML = `
    <strong>${isAm ? "✓ በራሱ የተነበበ መረጃ" : "✓ Auto-Parsed Transaction"}</strong>
    <div class="parsed-grid">
      <div><span>${isAm ? "ባንክ / አገልግሎት" : "Institution"}</span><strong>${tx.bank}</strong></div>
      <div><span>${isAm ? "መጠን" : "Amount"}</span><strong class="${tx.type === "income" ? "pos" : "neg"}">${tx.type === "income" ? "+" : "−"}${formatETB(tx.amount)} ETB</strong></div>
      <div><span>${isAm ? "ዓይነት" : "Type"}</span><strong>${typeLabel}</strong></div>
      <div><span>${isAm ? "ላኪ / ተቀባይ" : "Counterparty"}</span><strong>${tx.party}</strong></div>
    </div>
  `;
}

function renderLedger() {
  const listEl = document.getElementById("ledgerList");
  const query = document.getElementById("ledgerSearch").value.trim().toLowerCase();
  const typeFilter = document.getElementById("ledgerTypeFilter").value;

  const totalIn = ledger.filter((t) => t.type === "income").reduce((s, t) => s + t.amount, 0);
  const totalOut = ledger.filter((t) => t.type === "expense").reduce((s, t) => s + t.amount, 0);

  document.getElementById("demoTotalIn").textContent = `+${formatETB(totalIn)} ETB`;
  document.getElementById("demoTotalOut").textContent = `−${formatETB(totalOut)} ETB`;

  const filtered = ledger.filter((tx) => {
    const matchesType = typeFilter === "all" || tx.type === typeFilter;
    const matchesQuery =
      !query ||
      tx.party.toLowerCase().includes(query) ||
      tx.bank.toLowerCase().includes(query) ||
      String(tx.amount).includes(query);
    return matchesType && matchesQuery;
  });

  if (filtered.length === 0) {
    listEl.innerHTML = `<div class="ledger-item"><small>${currentLang === "am" ? "ምንም የሚመሳሰል ግብይት አልተገኘም።" : "No matching transactions found."}</small></div>`;
    return;
  }

  listEl.innerHTML = filtered
    .map(
      (tx) => `
      <div class="ledger-item">
        <div>
          <strong>${tx.party}</strong>
          <small>${tx.bank} · ${tx.date}</small>
        </div>
        <div class="tx-amt ${tx.type === "income" ? "pos" : "neg"}">
          ${tx.type === "income" ? "+" : "−"}${formatETB(tx.amount)} ETB
        </div>
      </div>
    `
    )
    .join("");
}

function trackMetaEvent(eventName, params = {}) {
  if (typeof window.fbq === "function") {
    window.fbq("track", eventName, params);
  }
  if (typeof window.gtag === "function") {
    window.gtag("event", eventName === "InitiateCheckout" ? "begin_checkout" : "view_item", params);
  }
}

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.title =
    lang === "am"
      ? "BirrFlow (ብርፍሎው) — የኢትዮጵያ የግል ፋይናንስ እና የባንክ SMS መከታተያ"
      : "BirrFlow — Ethiopian Personal Finance & Bank SMS Tracker";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (I18N[lang][key]) {
      el.innerHTML = I18N[lang][key];
    }
  });
  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang-btn") === lang);
  });
  const searchInput = document.getElementById("ledgerSearch");
  searchInput.placeholder =
    lang === "am" ? "ፈልግ (ምሳሌ፦ CBE, Telebirr, Dawit...)" : "Search (e.g. CBE, Telebirr, Dawit...)";

  const parsed = parseSms(document.getElementById("smsInput").value);
  renderParsedPreview(parsed);
  renderLedger();
}

